#[derive(Debug, PartialEq)]
pub enum Token<'a> {
    Sep,
    Add,
    Sub,
    Exp,
    Mul,
    Div,
    Colon,
    Eq,
    Equal,
    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Dot,
    Bool(bool),
    Int(i64),
    Float(f64),
    Str(&'a str),
    Id(&'a str),
}
